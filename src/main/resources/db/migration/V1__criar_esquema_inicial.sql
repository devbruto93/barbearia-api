CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_role CHECK (role IN ('CLIENTE', 'ADMIN'))
);

CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    telefone VARCHAR(255),
    usuario_id BIGINT,
    CONSTRAINT uk_clientes_telefone UNIQUE (telefone),
    CONSTRAINT uk_clientes_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_clientes_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id)
);

CREATE TABLE barbeiros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    telefone VARCHAR(255) NOT NULL,
    especialidade VARCHAR(255) NOT NULL,
    CONSTRAINT uk_barbeiros_telefone UNIQUE (telefone)
);

CREATE TABLE agendamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    barbeiro_id BIGINT NOT NULL,
    data_hora TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(255) NOT NULL,
    CONSTRAINT ck_agendamentos_status CHECK (status IN ('AGENDADO', 'CONCLUIDO', 'CANCELADO')),
    CONSTRAINT fk_agendamentos_cliente FOREIGN KEY (cliente_id)
        REFERENCES clientes (id) ON DELETE CASCADE,
    CONSTRAINT fk_agendamentos_barbeiro FOREIGN KEY (barbeiro_id)
        REFERENCES barbeiros (id) ON DELETE CASCADE
);

CREATE INDEX ix_agendamentos_barbeiro_data_hora
    ON agendamentos (barbeiro_id, data_hora);

CREATE INDEX ix_agendamentos_cliente_data_hora
    ON agendamentos (cliente_id, data_hora);
